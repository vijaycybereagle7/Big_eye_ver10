"""
DGA (Domain Generation Algorithm) Detector

Detects domains generated by Domain Generation Algorithms used by:
- Botnets
- Malware command and control
- Fast-flux networks
- Other malicious infrastructure
"""

import numpy as np
import pandas as pd
from typing import Dict, List, Tuple, Any, Optional
import re
from collections import Counter
import logging

from ..algorithms.autoencoder_detector_simple import AutoencoderDetector
from ..algorithms.isolation_forest_detector import IsolationForestDetector

logger = logging.getLogger(__name__)


class DGADetector:
    """Detector for Domain Generation Algorithm (DGA) generated domains."""

    def __init__(self, config: Dict[str, Any] = None):
        self.config = config or self._get_default_config()
        
        model_type = self.config.get('model', 'autoencoder')
        if model_type == 'autoencoder':
            self.detector = AutoencoderDetector(self.config.get('autoencoder_config', {}))
        elif model_type == 'isolation_forest':
            self.detector = IsolationForestDetector(self.config.get('isolation_forest_config', {}))
        else:
            self.detector = AutoencoderDetector(self.config.get('autoencoder_config', {}))
        
        self.threshold = self.config.get('threshold', 0.85)
        self.is_fitted = False

    def _get_default_config(self) -> Dict[str, Any]:
        return {
            'threshold': 0.85,
            'model': 'autoencoder',
            'features': [
                'char_frequency',
                'n_gram_analysis',
                'domain_structure',
                'entropy_score',
                'vowel_consonant_ratio',
                'length_score',
                'repeated_chars',
                'tld_analysis'
            ],
            'autoencoder_config': {
                'encoding_dim': 32,
                'epochs': 150,
                'batch_size': 64
            },
            'isolation_forest_config': {
                'contamination': 0.1,
                'n_estimators': 200
            }
        }

    def _extract_dga_features(self, domain_data: Dict[str, Any]) -> np.ndarray:
        """Extract features for DGA detection from domain data."""
        try:
            features = []
            domain = domain_data.get('domain', '').lower().split('.')[0]  # Remove TLD
            
            # 1. Character Frequency Analysis
            char_freq = self._analyze_character_frequency(domain)
            features.append(char_freq)
            
            # 2. N-gram Analysis
            ngram_score = self._analyze_ngrams(domain)
            features.append(ngram_score)
            
            # 3. Domain Structure
            structure_score = self._analyze_domain_structure(domain)
            features.append(structure_score)
            
            # 4. Entropy Score
            entropy = self._calculate_entropy(domain)
            features.append(entropy)
            
            # 5. Vowel-Consonant Ratio
            vowel_consonant_ratio = self._calculate_vowel_consonant_ratio(domain)
            features.append(vowel_consonant_ratio)
            
            # 6. Length Score
            length_score = self._analyze_length(domain)
            features.append(length_score)
            
            # 7. Repeated Characters
            repeated_chars_score = self._analyze_repeated_chars(domain)
            features.append(repeated_chars_score)
            
            # 8. TLD Analysis
            tld = domain_data.get('domain', '').lower().split('.')[-1] if '.' in domain_data.get('domain', '') else ''
            tld_score = self._analyze_tld(tld)
            features.append(tld_score)
            
            return np.array(features)
            
        except Exception as e:
            logger.error(f"Error extracting DGA features: {str(e)}")
            return np.zeros(len(self.config['features']))

    def _analyze_character_frequency(self, domain: str) -> float:
        """Analyze character frequency patterns."""
        if not domain:
            return 0.0
        
        char_counts = Counter(domain)
        total_chars = len(domain)
        
        # Check for unusual character distributions
        english_freq = {'e': 0.127, 't': 0.091, 'a': 0.082, 'o': 0.075, 'i': 0.070}
        domain_freq = {char: count/total_chars for char, count in char_counts.items() if char.isalpha()}
        
        # Calculate deviation from English frequency
        deviation = 0.0
        for char, freq in english_freq.items():
            if char in domain_freq:
                deviation += abs(freq - domain_freq[char])
        
        return min(deviation, 1.0)

    def _analyze_ngrams(self, domain: str) -> float:
        """Analyze n-gram patterns."""
        if len(domain) < 3:
            return 0.0
        
        # Check for meaningful bigrams and trigrams
        bigrams = [domain[i:i+2] for i in range(len(domain)-1)]
        trigrams = [domain[i:i+3] for i in range(len(domain)-2)]
        
        # Common English patterns that DGA might not generate
        common_bigrams = ['th', 'he', 'in', 'er', 'an', 're', 'nd', 'at', 'on', 'nt']
        common_trigrams = ['the', 'ing', 'her', 'hat', 'his', 'tha', 'ere', 'for', 'ent', 'ion']
        
        meaningful_bigrams = sum(1 for bg in bigrams if bg in common_bigrams)
        meaningful_trigrams = sum(1 for tg in trigrams if tg in common_trigrams)
        
        total_bigrams = len(bigrams)
        total_trigrams = len(trigrams)
        
        if total_bigrams + total_trigrams == 0:
            return 1.0  # High anomaly score for very short domains
        
        meaningful_ratio = (meaningful_bigrams + meaningful_trigrams) / (total_bigrams + total_trigrams)
        return 1.0 - meaningful_ratio  # Higher score for less meaningful patterns

    def _analyze_domain_structure(self, domain: str) -> float:
        """Analyze overall domain structure patterns."""
        if not domain:
            return 1.0
        
        # DGA characteristics
        has_hyphens = '-' in domain
        has_numbers = any(c.isdigit() for c in domain)
        has_mixed_case = any(c.isupper() for c in domain) and any(c.islower() for c in domain)
        
        # Score based on DGA-like characteristics
        score = 0.0
        if has_hyphens:
            score += 0.3
        if has_numbers:
            score += 0.2
        if has_mixed_case:
            score += 0.2
        
        # Check for natural language patterns
        english_patterns = ['tion', 'ing', 'ment', 'ness', 'able', 'less']
        if any(pattern in domain.lower() for pattern in english_patterns):
            score -= 0.4  # Reduce score for English-like patterns
        
        return max(0.0, min(score, 1.0))

    def _calculate_entropy(self, domain: str) -> float:
        """Calculate Shannon entropy of the domain."""
        if not domain:
            return 0.0
        
        char_counts = Counter(domain)
        entropy = -sum((count/len(domain)) * np.log2(count/len(domain)) 
                      for count in char_counts.values() if count > 0)
        
        # Normalize entropy (max for random string would be log2(26) for letters)
        max_entropy = np.log2(26)
        return min(entropy / max_entropy, 1.0)

    def _calculate_vowel_consonant_ratio(self, domain: str) -> float:
        """Calculate vowel-consonant ratio."""
        if not domain:
            return 0.5
        
        vowels = sum(1 for c in domain.lower() if c in 'aeiou')
        consonants = sum(1 for c in domain.lower() if c.isalpha() and c not in 'aeiou')
        
        if consonants == 0:
            return 1.0
        
        ratio = vowels / consonants
        
        # English domains typically have vowel-consonant ratio around 0.4-0.6
        # DGA domains often deviate from this
        deviation = abs(ratio - 0.5)
        return min(deviation * 2, 1.0)  # Scale deviation to 0-1

    def _analyze_length(self, domain: str) -> float:
        """Analyze domain length patterns."""
        if not domain:
            return 1.0
        
        length = len(domain)
        
        # Most legitimate domains are between 3-15 characters
        if 3 <= length <= 15:
            return 0.2  # Low anomaly score
        elif 16 <= length <= 25:
            return 0.5  # Medium anomaly score
        else:
            return 0.8  # High anomaly score

    def _analyze_repeated_chars(self, domain: str) -> float:
        """Analyze repeated character patterns."""
        if not domain:
            return 0.0
        
        # Count consecutive repeated characters
        max_consecutive = 1
        current_consecutive = 1
        
        for i in range(1, len(domain)):
            if domain[i] == domain[i-1]:
                current_consecutive += 1
                max_consecutive = max(max_consecutive, current_consecutive)
            else:
                current_consecutive = 1
        
        # DGA domains often have more repeated characters
        if max_consecutive >= 3:
            return 0.7
        elif max_consecutive >= 2:
            return 0.4
        else:
            return 0.1

    def _analyze_tld(self, tld: str) -> float:
        """Analyze TLD characteristics."""
        if not tld:
            return 0.5
        
        # Common legitimate TLDs
        legitimate_tlds = ['com', 'org', 'net', 'edu', 'gov', 'mil', 'info', 'biz']
        
        # TLDs commonly used by malware/botnets
        suspicious_tlds = ['tk', 'ml', 'cf', 'ga', 'xyz', 'top', 'click', 'country']
        
        if tld in legitimate_tlds:
            return 0.1
        elif tld in suspicious_tlds:
            return 0.8
        else:
            return 0.5

    def train(self, training_data: pd.DataFrame) -> Dict[str, Any]:
        """Train the DGA detector."""
        try:
            logger.info("Training DGA detector...")
            
            feature_matrix = []
            for _, row in training_data.iterrows():
                features = self._extract_dga_features(row.to_dict())
                feature_matrix.append(features)
            
            X = np.array(feature_matrix)
            self.detector.fit(X)
            self.is_fitted = True
            
            return {
                'status': 'trained',
                'model_type': self.config['model'],
                'features_used': self.config['features'],
                'training_samples': len(X),
                'model_info': self.detector.get_model_info()
            }
            
        except Exception as e:
            logger.error(f"Error training DGA detector: {str(e)}")
            return {'status': 'failed', 'error': str(e)}

    def detect(self, domain_data: List[Dict[str, Any]]) -> Dict[str, Any]:
        """Detect DGA-generated domains."""
        try:
            if not self.is_fitted:
                raise ValueError("Detector must be trained before detection")
            
            feature_matrix = []
            for domain in domain_data:
                features = self._extract_dga_features(domain)
                feature_matrix.append(features)
            
            X = np.array(feature_matrix)
            
            if hasattr(self.detector, 'get_anomaly_scores'):
                anomaly_scores = self.detector.get_anomaly_scores(X)
                anomaly_indices = np.where(anomaly_scores > self.threshold)[0].tolist()
                anomalies_detected = len(anomaly_indices) > 0
            else:
                anomaly_indices = []
                anomalies_detected = False
                anomaly_scores = np.zeros(len(X))
            
            return {
                'anomalies_detected': anomalies_detected,
                'anomaly_count': len(anomaly_indices),
                'total_domains': len(domain_data),
                'anomaly_rate': len(anomaly_indices) / len(domain_data) if domain_data else 0.0,
                'anomaly_indices': anomaly_indices,
                'anomaly_scores': anomaly_scores.tolist(),
                'threshold': self.threshold,
                'detected_domains': [
                    domain_data[i] for i in anomaly_indices if i < len(domain_data)
                ] if anomaly_indices else []
            }
            
        except Exception as e:
            logger.error(f"Error detecting DGA domains: {str(e)}")
            return {
                'anomalies_detected': False,
                'error': str(e),
                'anomaly_count': 0,
                'total_domains': len(domain_data) if domain_data else 0
            }